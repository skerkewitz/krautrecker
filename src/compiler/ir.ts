import type { DspEnvelope, EchoParams } from '../dsp/sdsp';
import type { DeviceId, PatternId, SampleId } from '../model/types';

/**
 * The IR: low-level, tick-resolution data for the 8 hardware voices. It is a build artifact,
 * regenerated from the project on every change, and never edited or saved.
 */

/** Where an IR event came from, so the UI can link back to the cell. */
export interface SourceRef {
  orderIndex: number;
  patternId: PatternId;
  track: number;
  line: number;
  column: number;
}

export interface KeyOnData {
  sampleSlot: number;
  pitch: number;
  volL: number;
  volR: number;
  envelope: DspEnvelope;
  echo: boolean;
}

interface EventBase {
  tick: number;
  source: SourceRef;
  /**
   * Generated by per-tick modulation (slides, vibrato) rather than written by the composer.
   * A real driver would compute these itself, so they do not count as song data.
   */
  auto?: boolean;
}

export interface KeyOnEvent extends EventBase, KeyOnData {
  type: 'keyOn';
  /** For display only: the note and device that produced this key-on. */
  note: number;
  deviceId: DeviceId;
  /** The note was cut short because another note stole its voice. */
  stolen?: boolean;
  /** The pitch had to be clamped to the 14-bit register range. */
  clamped?: boolean;
}

export type VoiceEvent =
  | KeyOnEvent
  | (EventBase & { type: 'keyOff' })
  | (EventBase & { type: 'setPitch'; pitch: number; clamped?: boolean })
  | (EventBase & { type: 'setVolume'; volL: number; volR: number })
  | (EventBase & {
      type: 'setEnvelope';
      envelope: DspEnvelope;
      /**
       * This switch starts the note's release (a GAIN decrease at note-off). The voice counts as
       * releasing from here; the key-off that follows once the envelope is at zero frees it at once.
       */
      release?: boolean;
    })
  /**
   * Noise on/off for this voice (NON). The noise clock itself is global: see 'noiseClock'.
   * `clock` is the clock the note asked for (display and diagnostics only; the register write is
   * the global event, and another note may have overwritten it).
   */
  | (EventBase & { type: 'noise'; enabled: boolean; clock?: number })
  /** Pitch modulation of this voice by the previous voice's output (PMON). */
  | (EventBase & { type: 'pitchMod'; enabled: boolean });

export type GlobalEvent =
  | { tick: number; type: 'tempo'; bpm: number }
  /** `auto`: a per-tick slide step (see EventBase.auto); not counted as song data. */
  | { tick: number; type: 'echo'; params: EchoParams; auto?: boolean }
  | { tick: number; type: 'mainVolume'; volL: number; volR: number; auto?: boolean }
  /** The global noise clock (FLG bits 0-4), 0..31. */
  | { tick: number; type: 'noiseClock'; clock: number }
  /** Echo buffer writes on/off (FLG bit 5). */
  | { tick: number; type: 'echoWrite'; enabled: boolean };

export type DiagnosticKind =
  | 'voiceStolen'
  | 'noteDropped'
  | 'pitchClamped'
  | 'noZone'
  | 'noDevice'
  | 'noSample'
  | 'loopRealigned'
  | 'aramOverBudget'
  | 'noiseClockConflict'
  | 'noiseOneShot'
  | 'pitchModUnavailable';

export interface Diagnostic {
  kind: DiagnosticKind;
  severity: 'info' | 'warning' | 'error';
  message: string;
  source?: SourceRef;
  tick?: number;
  voice?: number;
}

export interface LineInfo {
  orderIndex: number;
  patternId: PatternId;
  line: number;
  tick: number;
}

export interface AramEstimate {
  driver: number;
  directory: number;
  samples: { sampleId: SampleId; bytes: number }[];
  samplesTotal: number;
  echo: number;
  song: number;
  total: number;
  capacity: number;
}

export interface IR {
  timing: { bpm: number; linesPerBeat: number; ticksPerLine: number };
  totalTicks: number;
  /** Tick where playback continues after the end of the song (the order list's loop point). */
  loopTick: number;
  /** Exactly 8 lanes; reserved SFX voices stay empty. */
  voices: VoiceEvent[][];
  global: GlobalEvent[];
  /** Voice indices kept for sound effects. */
  reservedVoices: number[];
  /** Sample slot (directory index) -> sample ID. */
  sampleSlots: SampleId[];
  /** One entry per song line. */
  lines: LineInfo[];
  /** Per song line: hardware voices in use, and voices the music asked for. */
  voiceUsage: { used: number; demand: number }[];
  diagnostics: Diagnostic[];
  aram: AramEstimate;
}

export const VOICE_COUNT = 8;
export const ARAM_CAPACITY = 65536;
